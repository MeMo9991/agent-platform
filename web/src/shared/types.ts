export type Task = { id: string; title: string; scope: string; repoKey: string; originEventId?: string;
  state: string; iteration: number; priority: number; version: number; updatedAt: string;
  parentTaskId?: string; owner?: string; mandate: { goal: string; allowedActions: string[]; policyVersion: string;
    authority: { kind: 'trusted_rule' | 'auto_pr' | 'human_approval' } } };
export type ImageRef = { id: string; kind: string; mimeType?: string; imageUrl: string };
export type Event = { id: string; title: string; body: string; status: string; repoKey?: string;
  sourceId: string; receivedAt: string; url?: string; taskId?: string; attachments: ImageRef[];
  allowedRepoKeys?: string[]; repositorySelection?: 'repository-name' | 'file-name' | 'default';
  routing?: { reason?: string; candidates: { taskId: string; evidence?: unknown[] }[] } };
export type Run = { id: string; stage: string; status: string; sessionId?: string;
  agentKind?: string; model?: string; commitSha?: string; skillRef?: { path: string; commitSha: string };
  createdAt: string; endedAt?: string };
export type EvidenceFile = { recordId: string; available: boolean; bytes?: number; sha256?: string; truncated?: boolean };
export type RecordItem = { id: string; taskId: string; runId?: string; kind: string; at: string; status?: string; prompt?: string;
  content?: string; summary?: string; request?: { id: string; kind: string; sourceSha: string;
    action?: string; targetBranch?: string; targetSha?: string; changeRef?: string; reviewRecordId?: string;
    policyVersion?: string;
    proposedMandate?: { goal: string; allowedActions: string[]; maxAutoRisk?: string } }; reason?: string; from?: string;
  to?: string; questionId?: string; decision?: string; subjectSha?: string;
  baseSha?: string; commitSha?: string; codeChange?: 'none' | 'committed'; developmentRecordId?: string;
  postCheckVerified?: boolean; postCheckError?: string;
  diff?: EvidenceFile; log?: EvidenceFile; command?: string; args?: string[];
  result?: string; exitCode?: number | null; terminationConfirmed?: boolean;
  verdict?: 'pass' | 'block'; findingCount?: number; reviewRecordId?: string;
  targetSha?: string; changeId?: string; ready?: boolean; gate?: string; state?: string;
  action?: string; receipt?: { changeId: string; merged: boolean; mergedSha?: string;
    observedSourceSha: string; observedTargetSha: string };
  requiredChecks?: string[]; checks?: { name?: string; status: string; conclusion: string; commitSha: string }[];
  findingIndex?: number; disposition?: 'accept_risk' | 'false_positive'; file?: string; line?: number;
  severity?: string; evidence?: string; impact?: string; verificationMethod?: string; reviewer?: string };
export type ReviewFinding = { file: string; line?: number; severity: string; evidence: string;
  impact: string; action?: string; verificationMethod?: string };
export type Detail = { task: Task; runs: Run[]; records: RecordItem[]; events: Event[] };
